"""Generate a V80 interface wrapper from the frozen M3 port contract."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def generate(destination: Path):
    original = (ROOT / "third_party/v80-platform/m3/stage2/m3_lpu_wrapper.sv").read_text()
    header = original.split("\n);", 1)[0] + "\n);\n"
    header = header[header.index("module m3_lpu_wrapper"):].replace("module m3_lpu_wrapper", "module v80_opentpu_wrapper")
    # The real bridge has one outstanding AXI transaction. Dummy RV ports remain idle.
    header = header.replace("NUM_READ_OUTSTANDING 8", "NUM_READ_OUTSTANDING 1").replace(
        "NUM_WRITE_OUTSTANDING 8", "NUM_WRITE_OUTSTANDING 1")
    ports = re.findall(r"^(input|output) wire\s+(?:\[[^\]]+\]\s*)?(\w+)\s*,?\s*$", header, re.M)
    if not any(name == "M_AXI_AWADDR" for _, name in ports):
        raise ValueError("frozen M3 port declaration format changed")
    lines = ["// Generated by software/tools/prepare_board.py from the frozen M3 interface contract.",
             "// LPU/RVCore implementation is replaced; RV memory masters and old IRQs are idle.", header,
             "wire [31:0] logical_awaddr, logical_araddr;",
             "assign M_AXI_AWADDR = {8'h40, logical_awaddr};",
             "assign M_AXI_ARADDR = {8'h40, logical_araddr};"]
    connections = [".clk(core_clk)", ".rst(!core_resetn)"]
    for _, name in ports:
        if name.startswith("S_AXI_") and not name.endswith("PROT"):
            value = f"{name}[11:0]" if name.endswith("ADDR") else name
            connections.append(f".{name.lower()}({value})")
        elif name.startswith("M_AXI_"):
            suffix = name[6:]
            if suffix in ("AWID", "ARID", "AWLOCK", "ARLOCK", "AWCACHE", "ARCACHE", "AWPROT", "ARPROT",
                          "AWQOS", "ARQOS", "AWREGION", "ARREGION", "BID", "RID"):
                if dict((n, d) for d, n in ports)[name] == "output":
                    lines.append(f"assign {name} = '0;")
            else:
                value = "logical_awaddr" if suffix == "AWADDR" else "logical_araddr" if suffix == "ARADDR" else name
                connections.append(f".{name.lower()}({value})")
    for direction, name in ports:
        if direction == "output" and (name.startswith(("RV_", "rv_")) or name in ("rvcore_irq", "lpu_done_irq")):
            lines.append(f"assign {name} = '0;")
    lines.append("v80_opentpu_core compute (\n  " + ",\n  ".join(connections) + "\n);\nendmodule\n")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines))
    print(f"board wrapper: {len(ports)} ports; M3 platform shape, openTPU compute only")


if __name__ == "__main__":
    generate(ROOT / "hardware/rtl/top/v80_opentpu_wrapper.sv")
